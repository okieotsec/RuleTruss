def _macs(table):
    """OUI plus the address's last three octets, so no two addresses in the example share a MAC by accident."""
    return {ip: "{}:{:02x}:{:02x}:{:02x}".format(OUI[vendor], *(int(o) for o in ip.split(".")[1:])) for ip, vendor in table.items()}


